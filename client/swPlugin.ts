// Builds the service worker (src/sw.ts) into `sw.js` at the root of the output, with the build's file list and a
// version derived from the files' contents. Build only: the dev server has no service worker.
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, resolve, sep } from 'node:path'
import { transformWithEsbuild, type Plugin, type ResolvedConfig } from 'vite'

export const SW_FILE = 'sw.js'

/**
 * The files a client should keep for offline use, relative to the site root, in a stable order. Source maps and the
 * worker itself are left out; `index.html` comes first.
 */
export function precacheList(paths: string[]): string[] {
  const keep = paths
    .map((p) => p.split(sep).join('/').replace(/^\.?\//, ''))
    .filter((p) => p && p !== SW_FILE && !p.endsWith('.map') && !p.split('/').some((s) => s.startsWith('.')))
  return [...new Set(keep)].sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : a < b ? -1 : a > b ? 1 : 0))
}

/** A short version for the cache name: changes whenever any file's name or contents change. */
export function buildVersion(files: { path: string; bytes: Uint8Array }[]): string {
  const h = createHash('sha256')
  for (const f of [...files].sort((a, b) => (a.path < b.path ? -1 : 1))) h.update(f.path).update('\0').update(f.bytes).update('\0')
  return h.digest('hex').slice(0, 12)
}

/** The worker's source: the precache manifest, then the compiled worker. */
export function swSource(version: string, files: string[], worker: string): string {
  return `// mobdaw service worker, generated by client/swPlugin.ts. Do not edit.\nconst PRECACHE = ${JSON.stringify({ version, files })};\n${worker}`
}

async function walk(dir: string): Promise<string[]> {
  const out: string[] = []
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) out.push(...(await walk(p)))
    else if (e.isFile()) out.push(p)
  }
  return out
}

export function swPlugin(): Plugin {
  let config: ResolvedConfig
  return {
    name: 'mobdaw-sw',
    apply: 'build',
    configResolved(c) {
      config = c
    },
    // after everything is written (bundle + public/), so the list is exactly what gets deployed
    async closeBundle() {
      const outDir = resolve(config.root, config.build.outDir)
      const abs = await walk(outDir)
      const files = precacheList(abs.map((p) => relative(outDir, p)))
      const version = buildVersion(await Promise.all(files.map(async (path) => ({ path, bytes: await readFile(join(outDir, path)) }))))
      const src = await readFile(resolve(config.root, 'src/sw.ts'), 'utf8')
      const { code } = await transformWithEsbuild(src, 'sw.ts', { format: 'iife', target: 'es2020', minify: config.build.minify !== false })
      await writeFile(join(outDir, SW_FILE), swSource(version, files, code))
      config.logger.info(`  ${SW_FILE}: ${files.length} files precached, version ${version}`)
    },
  }
}
